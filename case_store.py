STORE_SCHEMA_VERSION = 1

#: Hard structural bounds. A local workbench still needs a ceiling: an owner pasting a
#: multi-megabyte document must get a typed refusal, not an unbounded in-memory store.
MAX_CASES = 50
MAX_SOURCES_PER_CASE = 20
MAX_FACTS_PER_CASE = 80
MAX_CLAIMS_PER_CASE = 50
MAX_TEXT_BYTES = 64 * 1024
MAX_EXACT_EXCERPT = 2000
MAX_REVISIONS_PER_CASE = 100

CAPTURE_CLASSES = ('USER_SUPPLIED_EXCERPT', 'INDEPENDENT_ORIGINAL_BYTES')
#: Only a human may mark a mapping reviewed. ``HUMAN_REVIEWED`` is the one state the Court treats
#: as eligible; the other states are kept so an edit never silently keeps an old approval.
FACT_REVIEW_STATES = ('PENDING_HUMAN_REVIEW', 'HUMAN_REVIEWED', 'SOURCE_REVISED_REVIEW_REQUIRED')
CONFIRMATION_STATES = ('UNCONFIRMED', 'CONFIRMED', 'INVALIDATED_STALE')

_ID_RE = re.compile(r'^[a-z][a-z0-9_]{0,39}$')
#: Human-declared references (subject/action/qualifier identifiers) follow the Court's grammar,
#: which permits dots, colons and hyphens so a real action id like ``J.1-res-2026-13`` is usable.
_REF_RE = re.compile(r'^[A-Za-z0-9_.:-]{1,128}$')
_SHA256_RE = re.compile(r'^[0-9a-f]{64}$')
_HOST_RE = re.compile(r'^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)+$')

_CLAIM_CONTENT_KEYS = (
    'text', 'predicate', 'subject_id', 'action_id', 'jurisdiction_id', 'fact_ids',
    'additional_record', 'amount_cents', 'phase', 'event_date', 'yea', 'nay', 'abstain',
    'ceiling', 'as_of',
)
_FACT_CONTENT_KEYS = (
    'source_id', 'anchor', 'exact_excerpt', 'predicate', 'subject_id', 'action_id',
    'jurisdiction_id', 'qualifiers', 'reported_at', 'amount_cents', 'phase', 'event_date',
    'yea', 'nay', 'abstain',
)
_FACT_VALUE_KEYS = ('amount_cents', 'phase', 'event_date', 'yea', 'nay', 'abstain')
_SOURCE_PATCH_FIELDS = frozenset({
    'title', 'official_url', 'document_role', 'document_date', 'as_of', 'anchor', 'exact_text',
})
_FACT_PATCH_FIELDS = frozenset({
    'anchor', 'exact_excerpt', 'predicate', 'subject_id', 'action_id', 'qualifiers',
    'review_state', 'reviewed_by', 'amount_cents', 'phase', 'event_date', 'yea', 'nay', 'abstain',
})
_CLAIM_PATCH_FIELDS = frozenset({
    'text', 'predicate', 'subject_id', 'action_id', 'fact_ids', 'additional_record',
    'amount_cents', 'phase', 'event_date', 'yea', 'nay', 'abstain', 'ceiling', 'as_of',
})


class CaseStoreError(ValueError):
    """Typed, bounded failure. ``code`` is stable for the HTTP layer; ``status`` is advisory."""

    def __init__(self, code: str, message: str, *, status: int = 422) -> None:
        super().__init__(message)
        self.code = code
        self.status = status

    def as_detail(self) -> dict[str, str]:
        return {'code': self.code, 'message': str(self)}


def _utc_now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def _canonical_sha256(payload: Any) -> str:
    return hashlib.sha256(
        json.dumps(payload, sort_keys=True, separators=(',', ':'), ensure_ascii=False).encode('utf-8')
    ).hexdigest()


def _record_digest(record: dict, keys: tuple[str, ...]) -> str:
    return _canonical_sha256({key: record.get(key) for key in keys})


def _case_digest(case: dict) -> str:
    return _canonical_sha256({key: value for key, value in case.items() if key != 'revisions'})


def normalise_excerpt(text: str) -> str:
    """Unicode-normalised, whitespace-collapsed form used for human review and containment.

    NFKC folds compatibility characters (for example the ``ﬂ`` ligature in the sample minutes)
    and casefold() removes case distinctions. It is a *review aid*, not a legal reading.
    """
    return ' '.join(unicodedata.normalize('NFKC', text).casefold().split())


def _require_str(value: Any, field: str, *, maximum: int, minimum: int = 1) -> str:
    if not isinstance(value, str):
        raise CaseStoreError('INVALID_INPUT', f'{field} must be a string')
    if not minimum <= len(value) <= maximum:
        raise CaseStoreError('INVALID_INPUT', f'{field} must be {minimum}-{maximum} characters')
    return value


def _optional_str(value: Any, field: str, *, maximum: int) -> str | None:
    if value is None:
        return None
    return _require_str(value, field, maximum=maximum)


def _require_id(value: Any, field: str) -> str:
    if not isinstance(value, str) or not _ID_RE.fullmatch(value):
        raise CaseStoreError('INVALID_INPUT', f'{field} is not a generated identifier')
    return value


def _require_ref(value: Any, field: str) -> str:
    if not isinstance(value, str) or not _REF_RE.fullmatch(value):
        raise CaseStoreError('INVALID_INPUT', f'{field} is not a valid reference identifier')
    return value


def _iso_date(value: Any, field: str) -> str:
    text = _require_str(value, field, maximum=10, minimum=10)
    try:
        parsed = date.fromisoformat(text)
    except ValueError:
        raise CaseStoreError('INVALID_INPUT', f'{field} must be an ISO date') from None
    if parsed.isoformat() != text:
        raise CaseStoreError('INVALID_INPUT', f'{field} must be an ISO date')
    return text


def _retrieved_date(value: Any) -> date:
    text = _require_str(value, 'retrieved_at_utc', maximum=40)
    try:
        return datetime.fromisoformat(text).date()
    except ValueError:
        raise CaseStoreError('INVALID_INPUT', 'retrieved_at_utc must be an ISO-8601 timestamp') from None


def _sha256(value: Any, field: str) -> str:
    if not isinstance(value, str) or not _SHA256_RE.fullmatch(value):
        raise CaseStoreError('INVALID_INPUT', f'{field} must be a lowercase SHA-256 hex digest')
    return value


def _text_bytes(text: str) -> bytes:
    encoded = text.encode('utf-8')
    if len(encoded) > MAX_TEXT_BYTES:
        raise CaseStoreError('SOURCE_TEXT_TOO_LARGE',
                             f'Imported text exceeds {MAX_TEXT_BYTES} UTF-8 bytes',
                             status=413)
    if not encoded.strip():
        raise CaseStoreError('EMPTY_SOURCE_TEXT', 'Imported text is empty', status=422)
    return encoded


def _bounded_int(value: Any, field: str, *, minimum: int = 0, maximum: int = 10_000_000_000) -> int:
    if type(value) is not int or not minimum <= value <= maximum:
        raise CaseStoreError('INVALID_INPUT', f'{field} must be an integer in range')
    return value


def _qualifiers(value: Any) -> list[str]:
    if value is None:
        return []
    if not isinstance(value, list) or len(value) > 16:
        raise CaseStoreError('INVALID_INPUT', 'qualifiers must be a list of at most 16 identifiers')
    for item in value:
        if not isinstance(item, str) or not _REF_RE.fullmatch(item):
            raise CaseStoreError('INVALID_INPUT', 'qualifier identifiers must match the reference grammar')
    return list(value)


def _record_refs(value: Any) -> list[dict]:
    if value is None:
        return []
    if not isinstance(value, list) or len(value) > 16:
        raise CaseStoreError('INVALID_INPUT', 'record_refs must be a list of at most 16 entries')
    refs = []
    for item in value:
        if not isinstance(item, dict):
            raise CaseStoreError('INVALID_INPUT', 'record_refs entries must be objects')
        extra = set(item) - {'tool', 'args', 'action_id'}
        if extra:
            raise CaseStoreError('INVALID_INPUT', 'record_refs entry has unknown fields')
        tool = _require_str(item.get('tool'), 'record_refs.tool', maximum=64)
        args = item.get('args')
        if not isinstance(args, dict) or not 1 <= len(args) <= 4:
            raise CaseStoreError('INVALID_INPUT', 'record_refs.args must be a non-empty object')
        clean_args = {}
        for key, arg_value in args.items():
            if not isinstance(key, str) or not _ID_RE.fullmatch(key):
                raise CaseStoreError('INVALID_INPUT', 'record_refs argument names must match the id grammar')
            if type(arg_value) not in (str, int) or (isinstance(arg_value, str) and len(arg_value) > 128):
                raise CaseStoreError('INVALID_INPUT', 'record_refs argument values must be bounded strings or ints')
            clean_args[key] = arg_value
        ref = {'tool': tool, 'args': clean_args}
        if item.get('action_id') is not None:
            ref['action_id'] = _require_ref(item['action_id'], 'record_refs.action_id')
        refs.append(ref)
    return refs


def _host_policy(publisher: Any, allowed_hosts: Any) -> dict:
    publisher_text = _require_str(publisher, 'publisher', maximum=200)
    if not isinstance(allowed_hosts, list) or not 1 <= len(allowed_hosts) <= 8:
        raise CaseStoreError('INVALID_INPUT', 'allowed_hosts must declare 1-8 hostnames')
    hosts = []
    for host in allowed_hosts:
        if not isinstance(host, str) or not _HOST_RE.fullmatch(host) or host != host.lower():
            raise CaseStoreError('INVALID_PUBLISHER_POLICY',
                                 'allowed_hosts entries must be lowercase DNS hostnames')
        if host not in hosts:
            hosts.append(host)
    return {'publisher': publisher_text, 'allowed_hosts': hosts}


def _official_url(value: Any, policy: dict) -> str:
    url = _require_str(value, 'official_url', maximum=1000, minimum=8)
    try:
        parts = urlsplit(url)
        host = (parts.hostname or '').lower()
    except ValueError:
        raise CaseStoreError('SOURCE_URL_NOT_ALLOWLISTED', 'Official source URL is not parseable') from None
    if parts.scheme != 'https' or not host or parts.username or parts.password:
        raise CaseStoreError('SOURCE_URL_NOT_ALLOWLISTED',
                             'Official source URL must be an https URL without credentials')
    if host not in policy['allowed_hosts']:
        raise CaseStoreError('SOURCE_URL_NOT_ALLOWLISTED',
                             'Official source URL host is not declared by this case policy')
    return url


def _publisher(value: Any, policy: dict) -> str:
    publisher = _require_str(value, 'publisher', maximum=200)
    if publisher != policy['publisher']:
        raise CaseStoreError('WRONG_PUBLISHER',
                             'Source publisher does not match this case publisher policy')
    return publisher


def _document_role(value: Any) -> str:
    role = _require_str(value, 'document_role', maximum=80)
    if role not in ALLOWED_DOCUMENT_ROLES:
        raise CaseStoreError('UNKNOWN_DOCUMENT_ROLE',
                             'document_role is not a recognised authority class')
    return role


def _claim_confirmation_digest(claim: dict) -> str:
    return _record_digest(claim, _CLAIM_CONTENT_KEYS)


def _fact_content_digest(fact: dict) -> str:
    return _record_digest(fact, _FACT_CONTENT_KEYS)


def _source_content_digest(source: dict) -> str:
    return _canonical_sha256({
        'title': source.get('title'),
        'official_url': source.get('official_url'),
        'publisher': source.get('publisher'),
        'document_role': source.get('document_role'),
        'document_date': source.get('document_date'),
        'as_of': source.get('as_of'),
        'anchor': source.get('anchor'),
        'capture_class': source.get('capture_class'),
        'content_sha256': source.get('content_sha256'),
        'raw_sha256': source.get('raw_sha256'),
    })


def _atomic_write(path: Path, payload: dict) -> None:
    """Write the whole document with temp + fsync + ``os.replace``; never a partial file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    data = (json.dumps(payload, sort_keys=True, separators=(',', ':'), ensure_ascii=False)
            + '\n').encode('utf-8')
    fd, temp_name = tempfile.mkstemp(prefix=path.name + '.tmp-', dir=str(path.parent))
    try:
        with os.fdopen(fd, 'wb') as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temp_name, path)
    except BaseException:
        try:
            os.unlink(temp_name)
        except OSError:
            pass
        raise
    try:
        dir_fd = os.open(str(path.parent), os.O_RDONLY)
    except OSError:
        return
    try:
        os.fsync(dir_fd)
    except OSError:
        pass  # Windows cannot fsync a directory handle; the rename is still atomic.
    finally:
        os.close(dir_fd)


def _empty_document() -> dict:
    return {'schema_version': STORE_SCHEMA_VERSION, 'store_revision': 0, 'cases': {}}


def _check_case_shape(case: Any, *, where: str) -> None:
    if not isinstance(case, dict):
        raise CaseStoreError('CASE_STORE_CORRUPT', f'{where} is not an object', status=500)
    for key in ('case_id', 'case_title', 'project_name', 'municipality', 'jurisdiction_id',
                'publisher_policy', 'audit', 'created_at_utc', 'updated_at_utc',
                'sources', 'facts', 'claims', 'revisions'):
        if key not in case:
            raise CaseStoreError('CASE_STORE_CORRUPT', f'{where} is missing {key}', status=500)
    if not isinstance(case['case_id'], str) or not _ID_RE.fullmatch(case['case_id']):
        raise CaseStoreError('CASE_STORE_CORRUPT', f'{where} has an invalid case id', status=500)
    if not isinstance(case['publisher_policy'], dict):
        raise CaseStoreError('CASE_STORE_CORRUPT', f'{where} has an invalid publisher policy', status=500)
    for name, limit in (('sources', MAX_SOURCES_PER_CASE), ('facts', MAX_FACTS_PER_CASE),
                        ('claims', MAX_CLAIMS_PER_CASE), ('revisions', MAX_REVISIONS_PER_CASE)):
        if not isinstance(case[name], list) or len(case[name]) > limit:
            raise CaseStoreError('CASE_STORE_CORRUPT', f'{where}.{name} is not a bounded list',
                                 status=500)
    for name, id_key in (('sources', 'source_id'), ('facts', 'fact_id'), ('claims', 'claim_id')):
        ids = []
        for entry in case[name]:
            if not isinstance(entry, dict) or not isinstance(entry.get(id_key), str):
                raise CaseStoreError('CASE_STORE_CORRUPT', f'{where}.{name} has a malformed entry',
                                     status=500)
            ids.append(entry[id_key])
        if len(set(ids)) != len(ids):
            raise CaseStoreError('CASE_STORE_CORRUPT', f'{where}.{name} has duplicate identifiers',
                                 status=500)
    if type(case.get('revision')) is not int or case['revision'] < 1:
        raise CaseStoreError('CASE_STORE_CORRUPT', f'{where} has an invalid revision', status=500)


class CaseStore:
    """One versioned JSON document holding every local case.

    ``path`` is chosen by the process, never by a request. Reads are deep copies so a caller
    cannot mutate the in-memory document without going through a mutation method (and therefore
    without a revision and an atomic write).
    """

    def __init__(self, path: str | Path, *, clock: Callable[[], str] | None = None) -> None:
        self.path = Path(path)
        self._clock = clock or _utc_now
        self._lock = threading.RLock()
        self._document = self._load()

    # -- persistence ------------------------------------------------------------------------

    def _load(self) -> dict:
        if not self.path.exists():
            return _empty_document()
        try:
            raw = self.path.read_text(encoding='utf-8')
        except (OSError, UnicodeDecodeError) as exc:
            raise CaseStoreError('CASE_STORE_UNREADABLE',
                                 f'Case store could not be read: {exc.__class__.__name__}',
                                 status=503) from None
        try:
            document = json.loads(raw)
        except json.JSONDecodeError:
            raise CaseStoreError('CASE_STORE_CORRUPT', 'Case store is not valid JSON',
                                 status=500) from None
        if not isinstance(document, dict):
            raise CaseStoreError('CASE_STORE_CORRUPT', 'Case store root must be an object', status=500)
        version = document.get('schema_version')
        if version != STORE_SCHEMA_VERSION:
            raise CaseStoreError('UNSUPPORTED_CASE_STORE_VERSION',
                                 'Case store schema version is not supported', status=500)
        if not isinstance(document.get('cases'), dict) or len(document['cases']) > MAX_CASES:
            raise CaseStoreError('CASE_STORE_CORRUPT', 'Case store case map is invalid', status=500)
        if type(document.get('store_revision')) is not int or document['store_revision'] < 0:
            raise CaseStoreError('CASE_STORE_CORRUPT', 'Case store revision is invalid', status=500)
        for case_id, case in document['cases'].items():
            _check_case_shape(case, where=f'cases[{case_id!r}]')
            if case['case_id'] != case_id:
                raise CaseStoreError('CASE_STORE_CORRUPT', 'Case key disagrees with case id',
                                     status=500)
        return document

    def _commit(self, case: dict) -> None:
        """Persist one validated candidate case, then publish it as authoritative memory.

        Ordering is the whole invariant of this module. ``_atomic_write`` either replaces the
        store file or leaves it exactly as it was; ``self._document`` is replaced only *after*
        that write returns. A candidate is a detached deep copy, so a validation error raised
        while it is being built can never reach authoritative memory, and a persistence failure
        raises before the memory swap, leaving excerpt, review state, confirmations, revision
        counter and the store file at their pre-call values.
        """
        cases = dict(self._document['cases'])
        cases[case['case_id']] = case
        self._commit_cases(cases)

    def _commit_cases(self, cases: dict) -> None:
        """Write a complete document image, then adopt it in memory (never the other way round)."""
        document = {
            'schema_version': STORE_SCHEMA_VERSION,
            'store_revision': int(self._document.get('store_revision', 0)) + 1,
            'cases': cases,
        }
        try:
            _atomic_write(self.path, document)
        except OSError as exc:
            raise CaseStoreError(
                'CASE_STORE_WRITE_FAILED',
                'Case store could not be written '
                f'({exc.__class__.__name__}); the case and the store file are unchanged',
                status=503) from None
        self._document = document

    def reload(self) -> None:
        with self._lock:
            self._document = self._load()

    def store_revision(self) -> int:
        return int(self._document.get('store_revision', 0))

    # -- read surface -----------------------------------------------------------------------

    def list_cases(self) -> dict:
        with self._lock:
            cases = [self._summary(case) for case in self._document['cases'].values()]
        cases.sort(key=lambda item: (item['created_at_utc'], item['case_id']))
        return {
            'schema_version': STORE_SCHEMA_VERSION,
            'store_revision': self.store_revision(),
            'state': 'CASES_PRESENT' if cases else 'NO_CASES_YET',
            'message': None if cases else 'No cases have been created in this local store yet.',
            'cases': cases,
        }

    @staticmethod
    def _summary(case: dict) -> dict:
        return {
            'case_id': case['case_id'],
            'case_title': case['case_title'],
            'project_name': case['project_name'],
            'municipality': case['municipality'],
            'revision': case['revision'],
            'state': case_state(case),
            'created_at_utc': case['created_at_utc'],
            'updated_at_utc': case['updated_at_utc'],
            'source_count': len(case['sources']),
            'fact_count': len(case['facts']),
            'claim_count': len(case['claims']),
            'audit': copy.deepcopy(case['audit']),
        }

    def get_case(self, case_id: str) -> dict:
        with self._lock:
            return copy.deepcopy(self._case(case_id))

    def get_revision(self, case_id: str, revision: int) -> dict:
        if type(revision) is not int or revision < 1:
            raise CaseStoreError('INVALID_INPUT', 'revision must be a positive integer')
        with self._lock:
            case = self._case(case_id)
            for entry in case['revisions']:
                if entry.get('revision') == revision:
                    return copy.deepcopy(entry)
        raise CaseStoreError('REVISION_NOT_FOUND', 'No such revision in this case history', status=404)

    def _case(self, case_id: str) -> dict:
        if not isinstance(case_id, str) or not _ID_RE.fullmatch(case_id):
            raise CaseStoreError('INVALID_CASE_ID', 'Case id is not a generated identifier', status=404)
        case = self._document['cases'].get(case_id)
        if case is None:
            raise CaseStoreError('CASE_NOT_FOUND', 'No such case in this local store', status=404)
        return case

    def _case_source(self, case: dict, source_id: str) -> dict:
        for source in case['sources']:
            if source['source_id'] == source_id:
                return source
        raise CaseStoreError('SOURCE_NOT_IN_CASE', 'Source does not belong to this case', status=404)

    def _case_fact(self, case: dict, fact_id: str) -> dict:
        for fact in case['facts']:
            if fact['fact_id'] == fact_id:
                return fact
        raise CaseStoreError('FACT_NOT_IN_CASE', 'Fact does not belong to this case', status=404)

    def _case_claim(self, case: dict, claim_id: str) -> dict:
        for claim in case['claims']:
            if claim['claim_id'] == claim_id:
                return claim
        raise CaseStoreError('CLAIM_NOT_IN_CASE', 'Claim does not belong to this case', status=404)

    # -- revision mechanics -----------------------------------------------------------------

    def _bump(self, case: dict, event: str, detail: dict) -> dict:
        now = self._clock()
        case['revision'] = int(case['revision']) + 1
        case['updated_at_utc'] = now
        entry = {
            'revision': case['revision'],
            'event': event,
            'at_utc': now,
            'detail': detail,
            'case_content_sha256': _case_digest(case),
        }
        case['revisions'].append(entry)
        if len(case['revisions']) > MAX_REVISIONS_PER_CASE:
            # Keep the creation record plus the most recent window; the report says exactly this.
            case['revisions'] = case['revisions'][:1] + case['revisions'][-(MAX_REVISIONS_PER_CASE - 1):]
        return entry

    def _invalidate_claims(self, case: dict, fact_ids: set[str], reason: str) -> list[str]:
        now = self._clock()
        touched = []
        for claim in case['claims']:
            if set(claim['fact_ids']) & fact_ids and claim['confirmation']['state'] == 'CONFIRMED':
                claim['confirmation'] = {
                    **claim['confirmation'],
                    'state': 'INVALIDATED_STALE',
                    'invalidated_at_utc': now,
                    'invalidation_reason': reason,
                }
                touched.append(claim['claim_id'])
        return touched

    # -- case creation ----------------------------------------------------------------------

    def create_case(self, *, project_name: Any, municipality: Any, case_title: Any,
                    jurisdiction_id: Any, publisher: Any, allowed_hosts: Any,
                    provenance_note: Any = None) -> dict:
        with self._lock:
            if len(self._document['cases']) >= MAX_CASES:
                raise CaseStoreError('CASE_LIMIT_REACHED',
                                     f'This local store already holds {MAX_CASES} cases',
                                     status=409)
            jurisdiction = _require_str(jurisdiction_id, 'jurisdiction_id', maximum=64)
            if not re.fullmatch(r'[a-z0-9][a-z0-9-]{0,63}', jurisdiction):
                raise CaseStoreError('INVALID_INPUT',
                                     'jurisdiction_id must be a lowercase slug')
            policy = _host_policy(publisher, allowed_hosts)
            now = self._clock()
            case = {
                'case_id': _new_id('case'),
                'schema_version': STORE_SCHEMA_VERSION,
                'case_title': _require_str(case_title, 'case_title', maximum=300),
                'project_name': _require_str(project_name, 'project_name', maximum=200),
                'municipality': _require_str(municipality, 'municipality', maximum=200),
                'jurisdiction_id': jurisdiction,
                'publisher_policy': policy,
                'audit': {
                    'original_source_verified': False,
                    'independent_fact_audit': 'PENDING',
                    'capture_basis': 'NO_SOURCE_IMPORTED_YET',
                    'provenance_note': (
                        _optional_str(provenance_note, 'provenance_note', maximum=500)
                        or 'Text in this case is user-supplied. Original document bytes have not '
                           'been verified and the facts have not been independently audited.'
                    ),
                },
                'created_at_utc': now,
                'updated_at_utc': now,
                'revision': 1,
                'sources': [],
                'facts': [],
                'claims': [],
                'revisions': [{
                    'revision': 1,
                    'event': 'CASE_CREATED',
                    'at_utc': now,
                    'detail': {'case_id': None,  # filled below, after the digest is stable
                               'case_title': case_title},
                    'case_content_sha256': None,
                }],
            }
            case['revisions'][0]['detail']['case_id'] = case['case_id']
            case['revisions'][0]['case_content_sha256'] = _case_digest(case)
            self._commit_cases({**self._document['cases'], case['case_id']: case})
            return copy.deepcopy(case)

    def discard_case(self, case_id: str) -> None:
        """Remove a just-created case whose first source could not be imported.

        Compensation only: it is used when ``POST /api/cases`` fails part-way through creating a
        case plus its first source, so a half-created shell is not left behind. Not exposed as an
        HTTP route.
        """
        with self._lock:
            case = self._case(case_id)
            cases = dict(self._document['cases'])
            del cases[case['case_id']]
            self._commit_cases(cases)

    # -- sources ----------------------------------------------------------------------------

    def add_source(self, case_id: str, *, title: Any, publisher: Any, official_url: Any,
                   document_role: Any, document_date: Any, as_of: Any, anchor: Any,
                   text: Any = None, capture_class: str = 'USER_SUPPLIED_EXCERPT',
                   raw_sha256: Any = None, retrieved_at_utc: Any = None,
                   record_refs: Any = None) -> dict:
        with self._lock:
            case = copy.deepcopy(self._case(case_id))
            if len(case['sources']) >= MAX_SOURCES_PER_CASE:
                raise CaseStoreError('SOURCE_LIMIT_REACHED',
                                     f'This case already holds {MAX_SOURCES_PER_CASE} sources',
                                     status=409)
            policy = case['publisher_policy']
            source = {
                'source_id': _new_id('src'),
                'case_id': case['case_id'],
                'title': _require_str(title, 'title', maximum=300),
                'publisher': _publisher(publisher, policy),
                'official_url': _official_url(official_url, policy),
                'document_role': _document_role(document_role),
                'document_date': _iso_date(document_date, 'document_date'),
                'as_of': _iso_date(as_of, 'as_of'),
                'anchor': _require_str(anchor, 'anchor', maximum=500),
                'capture_class': self._capture_class(capture_class),
                'retrieved_at_utc': _optional_str(retrieved_at_utc, 'retrieved_at_utc', maximum=40)
                                   or self._clock(),
                'original_source_verified': False,
                'independent_audit': 'PENDING',
                'review_state': 'PENDING_HUMAN_REVIEW',
                'record_refs': _record_refs(record_refs),
            }
            if source['capture_class'] == 'USER_SUPPLIED_EXCERPT':
                if raw_sha256 is not None:
                    raise CaseStoreError('IMPORTED_TEXT_CANNOT_CARRY_ORIGINAL_HASH',
                                         'Imported text must not declare an original-bytes hash')
                if not isinstance(text, str) or len(text) > MAX_TEXT_BYTES * 4:
                    raise CaseStoreError('INVALID_INPUT', 'text must be a bounded string')
                encoded = _text_bytes(text)
                source['exact_text'] = text
                source['content_sha256'] = hashlib.sha256(encoded).hexdigest()
                source['raw_sha256'] = None
                source['provenance_label'] = 'USER_SUPPLIED_EXCERPT__ORIGINAL_BYTES_UNVERIFIED'
            else:
                if text is not None:
                    raise CaseStoreError('ORIGINAL_BYTES_CAPTURE_NOT_TEXT',
                                         'An original-bytes source does not carry imported text')
                source['raw_sha256'] = _sha256(raw_sha256, 'raw_sha256')
                source['content_sha256'] = None
                source['exact_text'] = None
                source['provenance_label'] = 'CAPTURED_ORIGINAL_BYTES__INDEPENDENT_AUDIT_PENDING'
            if source['as_of'] > _retrieved_date(source['retrieved_at_utc']).isoformat():
                raise CaseStoreError('INVALID_INPUT', 'Source as_of is after its retrieval date')
            case['sources'].append(source)
            case['audit']['capture_basis'] = _capture_basis(case)
            self._bump(case, 'SOURCE_ADDED', {'source_id': source['source_id'],
                                              'capture_class': source['capture_class'],
                                              'content_sha256': source['content_sha256'],
                                              'raw_sha256': source['raw_sha256']})
            self._commit(case)
            return copy.deepcopy(source)

    @staticmethod
    def _capture_class(value: Any) -> str:
        if value not in CAPTURE_CLASSES:
            raise CaseStoreError('INVALID_CAPTURE_CLASS', 'Unknown source capture class')
        return value

    def update_source(self, case_id: str, source_id: str, patch: dict) -> dict:
        with self._lock:
            case = copy.deepcopy(self._case(case_id))
            source = self._case_source(case, _require_id(source_id, 'source_id'))
            if not isinstance(patch, dict) or not patch:
                raise CaseStoreError('INVALID_INPUT', 'Source patch must be a non-empty object')
            unknown = set(patch) - _SOURCE_PATCH_FIELDS
            if unknown:
                raise CaseStoreError('INVALID_INPUT', 'Source patch contains unknown fields')
            facts = [fact for fact in case['facts'] if fact['source_id'] == source['source_id']]
            if facts:
                # Fact mappings were reviewed against this source's date and authority class;
                # silently moving either would leave a Court that cannot be constructed.
                if 'as_of' in patch and patch['as_of'] != source['as_of']:
                    raise CaseStoreError('SOURCE_SEMANTICS_LOCKED_BY_FACTS',
                                         'Source as_of cannot change while fact mappings cite it',
                                         status=409)
                if 'document_role' in patch and patch['document_role'] != source['document_role']:
                    raise CaseStoreError('SOURCE_SEMANTICS_LOCKED_BY_FACTS',
                                         'Source document_role cannot change while facts cite it',
                                         status=409)
            policy = case['publisher_policy']
            changed = sorted(patch)
            before_source = _source_content_digest(source)
            text_changed = False
            for field, value in patch.items():
                if field == 'title':
                    source['title'] = _require_str(value, 'title', maximum=300)
                elif field == 'official_url':
                    source['official_url'] = _official_url(value, policy)
                elif field == 'document_role':
                    source['document_role'] = _document_role(value)
                elif field == 'document_date':
                    source['document_date'] = _iso_date(value, 'document_date')
                elif field == 'as_of':
                    source['as_of'] = _iso_date(value, 'as_of')
                elif field == 'anchor':
                    source['anchor'] = _require_str(value, 'anchor', maximum=500)
                elif field == 'exact_text':
                    if source['capture_class'] != 'USER_SUPPLIED_EXCERPT':
                        raise CaseStoreError('CAPTURE_CLASS_IMMUTABLE',
                                             'Original-bytes sources cannot take imported text')
                    encoded = _text_bytes(_require_str(value, 'text', maximum=MAX_TEXT_BYTES * 4))
                    if value != source.get('exact_text'):
                        source['exact_text'] = value
                        source['content_sha256'] = hashlib.sha256(encoded).hexdigest()
                        text_changed = True
            if source['as_of'] > _retrieved_date(source['retrieved_at_utc']).isoformat():
                raise CaseStoreError('INVALID_INPUT', 'Source as_of is after its retrieval date')
            if text_changed:
                for fact in facts:
                    fact['review_state'] = 'SOURCE_REVISED_REVIEW_REQUIRED'
            content_changed = before_source != _source_content_digest(source)
            invalidated = (self._invalidate_claims(case, {fact['fact_id'] for fact in facts},
                                                   'SOURCE_REVISED')
                           if content_changed else [])
            case['audit']['capture_basis'] = _capture_basis(case)
            self._bump(case, 'SOURCE_UPDATED', {
                'source_id': source['source_id'], 'changed': changed,
                'text_changed': text_changed,
                'content_changed': content_changed,
                'facts_flagged_stale': sorted(fact['fact_id'] for fact in facts),
                'claims_invalidated': invalidated,
                'content_sha256': source['content_sha256'],
            })
            self._commit(case)
            return copy.deepcopy(source)

    def delete_source(self, case_id: str, source_id: str) -> dict:
        with self._lock:
            case = copy.deepcopy(self._case(case_id))
            source = self._case_source(case, _require_id(source_id, 'source_id'))
            dependents = sorted(fact['fact_id'] for fact in case['facts']
                                if fact['source_id'] == source['source_id'])
            if dependents:
                raise CaseStoreError('SOURCE_IN_USE',
                                     'Source still has fact mappings; delete or re-point them first',
                                     status=409)
            case['sources'].remove(source)
            case['audit']['capture_basis'] = _capture_basis(case)
            self._bump(case, 'SOURCE_DELETED', {'source_id': source['source_id']})
            self._commit(case)
            return {'case_id': case['case_id'], 'deleted_source_id': source['source_id'],
                    'revision': case['revision']}

