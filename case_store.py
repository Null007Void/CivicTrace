    def add_fact(self, case_id: str, *, source_id: Any, anchor: Any, exact_excerpt: Any,
                 predicate: Any, subject_id: Any, action_id: Any, qualifiers: Any = None,
                 review_state: str = 'PENDING_HUMAN_REVIEW', reviewed_by: Any = None,
                 amount_cents: Any = None, phase: Any = None, event_date: Any = None,
                 yea: Any = None, nay: Any = None, abstain: Any = None) -> dict:
        with self._lock:
            case = copy.deepcopy(self._case(case_id))
            if len(case['facts']) >= MAX_FACTS_PER_CASE:
                raise CaseStoreError('FACT_LIMIT_REACHED',
                                     f'This case already holds {MAX_FACTS_PER_CASE} facts',
                                     status=409)
            source = self._case_source(case, _require_id(source_id, 'source_id'))
            fact = {
                'fact_id': _new_id('fact'),
                'case_id': case['case_id'],
                'source_id': source['source_id'],
                'anchor': _require_str(anchor, 'anchor', maximum=500),
                'exact_excerpt': _require_str(exact_excerpt, 'exact_excerpt',
                                              maximum=MAX_EXACT_EXCERPT),
                'predicate': _predicate(predicate),
                'subject_id': _require_ref(subject_id, 'subject_id'),
                'action_id': _require_ref(action_id, 'action_id'),
                'jurisdiction_id': case['jurisdiction_id'],
                'qualifiers': _qualifiers(qualifiers),
                'reported_at': source['as_of'],
                'review_state': _review_state(review_state),
                'reviewed_by': _optional_str(reviewed_by, 'reviewed_by', maximum=120),
                'created_at_utc': self._clock(),
                'updated_at_utc': None,
            }
            self._apply_fact_values(fact, {'amount_cents': amount_cents, 'phase': phase,
                                           'event_date': event_date, 'yea': yea, 'nay': nay,
                                           'abstain': abstain})
            _require_role_match(fact, source)
            fact['normal_forms'] = _normal_forms(fact['exact_excerpt'])
            if not _excerpt_in_text(fact['exact_excerpt'], source):
                raise CaseStoreError('EXCERPT_NOT_IN_SOURCE',
                                     'Exact excerpt does not occur in the imported source text')
            case['facts'].append(fact)
            self._bump(case, 'FACT_ADDED', {'fact_id': fact['fact_id'],
                                            'source_id': source['source_id'],
                                            'predicate': fact['predicate'],
                                            'review_state': fact['review_state'],
                                            'content_sha256': _fact_content_digest(fact)})
            self._commit(case)
            return copy.deepcopy(fact)

    def update_fact(self, case_id: str, fact_id: str, patch: dict) -> dict:
        with self._lock:
            case = copy.deepcopy(self._case(case_id))
            fact = self._case_fact(case, _require_id(fact_id, 'fact_id'))
            if not isinstance(patch, dict) or not patch:
                raise CaseStoreError('INVALID_INPUT', 'Fact patch must be a non-empty object')
            unknown = set(patch) - _FACT_PATCH_FIELDS
            if unknown:
                raise CaseStoreError('INVALID_INPUT', 'Fact patch contains unknown fields')
            before = _fact_content_digest(fact)
            for field, value in patch.items():
                if field == 'anchor':
                    fact['anchor'] = _require_str(value, 'anchor', maximum=500)
                elif field == 'exact_excerpt':
                    fact['exact_excerpt'] = _require_str(value, 'exact_excerpt',
                                                        maximum=MAX_EXACT_EXCERPT)
                elif field == 'predicate':
                    fact['predicate'] = _predicate(value)
                elif field == 'subject_id':
                    fact['subject_id'] = _require_ref(value, 'subject_id')
                elif field == 'action_id':
                    fact['action_id'] = _require_ref(value, 'action_id')
                elif field == 'qualifiers':
                    fact['qualifiers'] = _qualifiers(value)
                elif field == 'review_state':
                    fact['review_state'] = _review_state(value)
                elif field == 'reviewed_by':
                    fact['reviewed_by'] = _optional_str(value, 'reviewed_by', maximum=120)
                elif field in _FACT_VALUE_KEYS:
                    self._apply_fact_values(fact, {field: value})
            source = self._case_source(case, fact['source_id'])
            _require_role_match(fact, source)
            fact['normal_forms'] = _normal_forms(fact['exact_excerpt'])
            if not _excerpt_in_text(fact['exact_excerpt'], source):
                raise CaseStoreError('EXCERPT_NOT_IN_SOURCE',
                                     'Exact excerpt does not occur in the imported source text')
            after = _fact_content_digest(fact)
            content_changed = before != after
            invalidated = []
            if content_changed:
                fact['review_state'] = 'SOURCE_REVISED_REVIEW_REQUIRED' if fact['review_state'] == 'HUMAN_REVIEWED' else fact['review_state']
                invalidated = self._invalidate_claims(case, {fact['fact_id']}, 'FACT_MAPPING_REVISED')
                fact['updated_at_utc'] = self._clock()
            self._bump(case, 'FACT_REVIEWED' if not content_changed else 'FACT_UPDATED', {
                'fact_id': fact['fact_id'], 'content_changed': content_changed,
                'review_state': fact['review_state'],
                'claims_invalidated': invalidated,
                'content_sha256': after,
            })
            self._commit(case)
            return copy.deepcopy(fact)

    def delete_fact(self, case_id: str, fact_id: str) -> dict:
        with self._lock:
            case = copy.deepcopy(self._case(case_id))
            fact = self._case_fact(case, _require_id(fact_id, 'fact_id'))
            affected = []
            for claim in case['claims']:
                if fact['fact_id'] in claim['fact_ids']:
                    claim['fact_ids'] = [item for item in claim['fact_ids']
                                         if item != fact['fact_id']]
                    if claim['confirmation']['state'] == 'CONFIRMED':
                        claim['confirmation'] = {
                            **claim['confirmation'],
                            'state': 'INVALIDATED_STALE',
                            'invalidated_at_utc': self._clock(),
                            'invalidation_reason': 'FACT_DELETED',
                        }
                    affected.append(claim['claim_id'])
            case['facts'].remove(fact)
            self._bump(case, 'FACT_DELETED', {'fact_id': fact['fact_id'],
                                              'claims_invalidated': affected})
            self._commit(case)
            return {'case_id': case['case_id'], 'deleted_fact_id': fact['fact_id'],
                    'revision': case['revision'], 'claims_invalidated': affected}

