"""Versioned, atomic, case-scoped JSON store for the CivicTrace case workbench.

Scope of this module (CT-WB1, part 1 of the reusable workbench)
-------------------------------------------------------------
A *case* is one municipality / project the owner is documenting. It owns its sources, the
human-reviewed fact mappings that quote those sources, and the structured claims built on those
facts. Nothing here is case-global: every mutating method takes a case id and every lookup is
resolved inside that case only.

Durability class
----------------
Same class as the other local state in this repository: a single JSON document written with
``tempfile`` + ``os.replace`` in the store's own directory, flushed and fsynced before the rename,
so a crash leaves either the previous document or the new one, never a torn file. Writes are
serialised per store instance with a re-entrant lock. Multi-process concurrent writers are *not*
coordinated beyond that; the workbench is a single owner process, and the report says so.

Every mutation is one transaction (CT-QC-060). The method builds and validates a detached deep
copy of the case, and only a fully validated candidate is committed: the complete new document is
written first and authoritative memory is replaced only after that write returns. A validation
error therefore cannot reach memory, and a persistence failure leaves memory, revisions and the
file at their pre-call state.

Honesty rules encoded here
--------------------------
* Identifiers are generated by this module (``case_<hex>``, ``src_<hex>``, ``fact_<hex>``,
  ``claim_<hex>``). A caller can never supply an id, a filesystem path, or a content hash that
  this module would trust.
* ``USER_SUPPLIED_EXCERPT`` text is exactly what the owner pasted or uploaded. Its
  ``content_sha256`` is the SHA-256 of the imported text bytes. It is never presented as an
  original-document hash and it never sets ``original_source_verified``.
* ``INDEPENDENT_ORIGINAL_BYTES`` is a separate capture class reserved for a source whose original
  bytes were captured and hashed elsewhere. It is not reachable from the workbench HTTP surface.
* Every mutation bumps the case revision and appends a revision record carrying the case content
  digest; a source or fact edit that a confirmed claim depended on invalidates that confirmation
  with ``INVALIDATED_STALE`` and records the cascade in the same revision.
* Empty / draft states are typed (``DRAFT_NO_SOURCES``, ``DRAFT_NO_CLAIMS``, ``NO_CASES_YET``)
  rather than filled with invented defaults.
"""
